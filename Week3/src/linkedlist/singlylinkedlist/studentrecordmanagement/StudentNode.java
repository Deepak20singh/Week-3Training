package linkedlist.singlylinkedlist.studentrecordmanagement;

public class StudentNode {
    int rollNumber, age;
    String name, grade;
    StudentNode next;

    // Constructor for StudentNode
    StudentNode(int rollNumber, int age, String name, String grade) {
        this.rollNumber = rollNumber;
        this.age = age;
        this.name = name;
        this.grade = grade;
        this.next = null;
    }
}
